class TwinResult {
  final String key;
  final String emoji;
  final String name;
  final String line;
  final String zinger;
  final List<String> tags;
  final String mission;

  const TwinResult({
    required this.key,
    required this.emoji,
    required this.name,
    required this.line,
    required this.zinger,
    required this.tags,
    required this.mission,
  });
}
